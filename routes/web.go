package routes

import (
	nethttp "net/http"

	"github.com/goravel/framework/contracts/http"
	"github.com/goravel/framework/contracts/route"
	httpmiddleware "github.com/goravel/framework/http/middleware"
	sessionmiddleware "github.com/goravel/framework/session/middleware"

	"neoskin/app/facades"
	"neoskin/app/http/controllers"
	oauthmw "neoskin/app/http/middleware"
	"neoskin/internal/plugin"
)

func Web() {
	facades.Route().Get("/__neoskin/health", func(ctx http.Context) http.Response {
		return ctx.Response().String(200, "ok")
	})

	homeController := controllers.NewHomeController()
	facades.Route().Get("/lang/:file", homeController.LangJS)

	textures := controllers.NewTextureController()
	facades.Route().Get("/textures/:hash", textures.Texture)
	facades.Route().Get("/csl/textures/:hash", textures.Texture)
	facades.Route().Get("/csl/:player", textures.PlayerJSON)
	facades.Route().Get("/raw/:tid", textures.Raw)
	facades.Route().Get("/avatar/hash/:hash", textures.AvatarByHash)
	facades.Route().Get("/avatar/player/:name", textures.AvatarByPlayer)
	facades.Route().Get("/avatar/user/:uid", textures.AvatarByUser)
	facades.Route().Get("/avatar/:tid", textures.AvatarByTexture)
	facades.Route().Get("/preview/hash/:hash", textures.PreviewByHash)
	facades.Route().Get("/preview/:texture", textures.Preview)
	facades.Route().Any("/.well-known/change-password", func(ctx http.Context) http.Response {
		return ctx.Response().Redirect(nethttp.StatusFound, "/user/profile")
	})
	ignitionController := controllers.NewIgnitionController()
	facades.Route().Get("/_ignition/health-check", ignitionController.HealthCheck)
	facades.Route().Post("/_ignition/execute-solution", ignitionController.ExecuteSolution)
	facades.Route().Post("/_ignition/update-config", ignitionController.UpdateConfig)

	oauthController := controllers.NewOAuthController()
	facades.Route().Post("/oauth/token", oauthController.Token)

	// Hook::pushMiddleware 追加的全局中间件挂在链尾（Laravel pushMiddleware
	// 追加到全局栈末尾；Go 约定在路由注册前 push）。
	groupMiddlewares := append([]http.Middleware{
		sessionmiddleware.StartSession(),
		oauthmw.DetectLocale("zh_CN"),
		oauthmw.NormalizeJSONContentType(),
		// Laravel 的 api 中间件组不校验 CSRF；第三方以 Bearer token 调用 /api/* 时同样不带 CSRF。
		httpmiddleware.VerifyCsrfToken([]string{"api", "api/*"}),
		// RouteServiceProvider：api 中间件组在生产环境带 throttle:60,1（testing 跳过）。
		oauthmw.APIThrottle(60),
	}, plugin.DefaultHook.PushedMiddlewares()...)
	web := facades.Route().Middleware(groupMiddlewares...)
	web.Group(func(router route.Router) {
		router.Get("/", homeController.Index)
		authController := controllers.NewAuthController()
		apiController := controllers.NewApiController()
		userController := controllers.NewUserController()
		playerController := controllers.NewPlayerController()
		closetController := controllers.NewClosetController()
		skinlibController := controllers.NewSkinlibController()
		reportController := controllers.NewReportController()
		adminUsersController := controllers.NewAdminUsersController()
		adminPlayersController := controllers.NewAdminPlayersController()
		adminClosetController := controllers.NewAdminClosetController()
		adminOptionsController := controllers.NewAdminOptionsController()
		translationsController := controllers.NewTranslationsController()
		communicationsController := controllers.NewCommunicationsController()
		notificationController := controllers.NewNotificationController()
		adminController := controllers.NewAdminController()
		pluginController := controllers.NewPluginController()
		marketController := controllers.NewMarketController()
		updateController := controllers.NewUpdateController()
		setupController := controllers.NewSetupController()
		oauthController := controllers.NewOAuthController()
		router.Get("/auth/login", authController.LoginPage)
		router.Post("/auth/login", authController.Login)
		router.Post("/auth/logout", authController.Logout)
		router.Get("/auth/register", authController.RegisterPage)
		router.Post("/auth/register", authController.Register)
		router.Any("/auth/captcha", authController.Captcha)
		router.Get("/auth/forgot", authController.Forgot)
		router.Post("/auth/forgot", authController.HandleForgot)
		router.Get("/auth/reset/:uid", authController.Reset)
		router.Post("/auth/reset/:uid", authController.HandleReset)
		router.Get("/auth/verify/:user", authController.Verify)
		router.Post("/auth/verify/:user", authController.HandleVerify)
		router.Get("/auth/bind", authController.BindPage)
		router.Post("/auth/bind", authController.Bind)
		router.Post("/user/email-verification", authController.SendVerification)
		router.Get("/setup", setupController.Show)
		router.Any("/setup/database", setupController.Database)
		router.Get("/setup/info", setupController.Info)
		router.Post("/setup/finish", setupController.Finish)
		router.Any("/api", apiController.Root)
		router.Middleware(oauthmw.RequireScopes("User.Read")).Get("/api/user", authController.User)
		router.Middleware(oauthmw.RequireScopes("Player.Read", "Player.ReadWrite")).Get("/api/players", playerController.List)
		router.Middleware(oauthmw.RequireScopes("Player.ReadWrite")).Post("/api/players", playerController.Add)
		router.Middleware(oauthmw.RequireScopes("Player.ReadWrite")).Delete("/api/players/:player", playerController.Delete)
		router.Middleware(oauthmw.RequireScopes("Player.ReadWrite")).Put("/api/players/:player/name", playerController.Rename)
		router.Middleware(oauthmw.RequireScopes("Player.ReadWrite")).Put("/api/players/:player/textures", playerController.SetTextures)
		router.Middleware(oauthmw.RequireScopes("Player.ReadWrite")).Delete("/api/players/:player/textures", playerController.ClearTextures)
		router.Get("/user/player", userController.PlayerPage)
		router.Get("/user/player/list", playerController.List)
		router.Post("/user/player", playerController.Add)
		router.Delete("/user/player/:player", playerController.Delete)
		router.Put("/user/player/:player/name", playerController.Rename)
		router.Put("/user/player/:player/textures", playerController.SetTextures)
		router.Delete("/user/player/:player/textures", playerController.ClearTextures)
		router.Middleware(oauthmw.RequireScopes("Closet.Read", "Closet.ReadWrite")).Get("/api/closet", closetController.List)
		router.Middleware(oauthmw.RequireScopes("Closet.Read", "Closet.ReadWrite")).Get("/api/closet/ids", closetController.IDs)
		router.Middleware(oauthmw.RequireScopes("Closet.ReadWrite")).Post("/api/closet", closetController.Add)
		router.Middleware(oauthmw.RequireScopes("Closet.ReadWrite")).Put("/api/closet/:tid", closetController.Rename)
		router.Middleware(oauthmw.RequireScopes("Closet.ReadWrite")).Delete("/api/closet/:tid", closetController.Remove)
		router.Get("/user/closet", userController.ClosetPage)
		router.Get("/user/closet/list", closetController.List)
		router.Get("/user/closet/ids", closetController.IDs)
		router.Post("/user/closet", closetController.Add)
		router.Put("/user/closet/:tid", closetController.Rename)
		router.Delete("/user/closet/:tid", closetController.Remove)
		router.Get("/skinlib", skinlibController.IndexPage)
		router.Get("/skinlib/list", skinlibController.Library)
		router.Get("/skinlib/info/:texture", skinlibController.Info)
		router.Get("/skinlib/show/:texture", skinlibController.ShowPage)
		router.Get("/skinlib/upload", skinlibController.UploadPage)
		router.Get("/texture/:texture", skinlibController.Info)
		router.Post("/texture", skinlibController.Upload)
		// PHP 皮肤库分组另有 POST /skinlib（与 POST /texture 同一处理器）。
		router.Post("/skinlib", skinlibController.Upload)
		router.Delete("/texture/:texture", skinlibController.Delete)
		router.Put("/texture/:texture/name", skinlibController.Rename)
		router.Put("/texture/:texture/privacy", skinlibController.Privacy)
		router.Put("/texture/:texture/type", skinlibController.Type)
		router.Post("/skinlib/report", reportController.Submit)
		router.Get("/user/reports", userController.ReportsPage)
		router.Get("/admin/reports", adminController.ReportsPage)
		router.Get("/admin/reports/list", reportController.Manage)
		router.Middleware(oauthmw.RequireScopes("ReportsManagement.Read", "ReportsManagement.ReadWrite")).Get("/api/admin/reports", reportController.Manage)
		router.Put("/admin/reports/:report", reportController.Review)
		router.Middleware(oauthmw.RequireScopes("ReportsManagement.ReadWrite")).Put("/api/admin/reports/:report", reportController.Review)
		router.Get("/admin/users", adminController.UsersPage)
		router.Get("/admin/users/list", adminUsersController.List)
		router.Middleware(oauthmw.RequireScopes("UsersManagement.Read", "UsersManagement.ReadWrite")).Get("/api/admin/users", adminUsersController.List)
		router.Delete("/admin/users/:user", adminUsersController.Delete)
		router.Middleware(oauthmw.RequireScopes("UsersManagement.ReadWrite")).Delete("/api/admin/users/:user", adminUsersController.Delete)
		router.Put("/admin/users/:user/email", adminUsersController.Email)
		router.Middleware(oauthmw.RequireScopes("UsersManagement.ReadWrite")).Put("/api/admin/users/:user/email", adminUsersController.Email)
		router.Put("/admin/users/:user/nickname", adminUsersController.Nickname)
		router.Middleware(oauthmw.RequireScopes("UsersManagement.ReadWrite")).Put("/api/admin/users/:user/nickname", adminUsersController.Nickname)
		router.Put("/admin/users/:user/password", adminUsersController.Password)
		router.Middleware(oauthmw.RequireScopes("UsersManagement.ReadWrite")).Put("/api/admin/users/:user/password", adminUsersController.Password)
		router.Put("/admin/users/:user/permission", adminUsersController.Permission)
		router.Middleware(oauthmw.RequireScopes("UsersManagement.ReadWrite")).Put("/api/admin/users/:user/permission", adminUsersController.Permission)
		router.Put("/admin/users/:user/score", adminUsersController.Score)
		router.Middleware(oauthmw.RequireScopes("UsersManagement.ReadWrite")).Put("/api/admin/users/:user/score", adminUsersController.Score)
		router.Put("/admin/users/:user/verification", adminUsersController.Verification)
		router.Middleware(oauthmw.RequireScopes("UsersManagement.ReadWrite")).Put("/api/admin/users/:user/verification", adminUsersController.Verification)
		router.Get("/admin/players", adminController.PlayersPage)
		router.Get("/admin/players/list", adminPlayersController.List)
		router.Middleware(oauthmw.RequireScopes("PlayersManagement.Read", "PlayersManagement.ReadWrite")).Get("/api/admin/players", adminPlayersController.List)
		router.Delete("/admin/players/:player", adminPlayersController.Delete)
		router.Middleware(oauthmw.RequireScopes("PlayersManagement.ReadWrite")).Delete("/api/admin/players/:player", adminPlayersController.Delete)
		router.Put("/admin/players/:player/name", adminPlayersController.Name)
		router.Middleware(oauthmw.RequireScopes("PlayersManagement.ReadWrite")).Put("/api/admin/players/:player/name", adminPlayersController.Name)
		router.Put("/admin/players/:player/owner", adminPlayersController.Owner)
		router.Middleware(oauthmw.RequireScopes("PlayersManagement.ReadWrite")).Put("/api/admin/players/:player/owner", adminPlayersController.Owner)
		router.Put("/admin/players/:player/textures", adminPlayersController.Texture)
		router.Middleware(oauthmw.RequireScopes("PlayersManagement.ReadWrite")).Put("/api/admin/players/:player/textures", adminPlayersController.Texture)
		router.Get("/admin/closet/:user", adminClosetController.List)
		router.Post("/admin/closet/:user", adminClosetController.Add)
		router.Delete("/admin/closet/:user", adminClosetController.Remove)
		router.Middleware(oauthmw.RequireScopes("ClosetManagement.Read", "ClosetManagement.ReadWrite")).Get("/api/admin/closet/:user", adminClosetController.List)
		router.Middleware(oauthmw.RequireScopes("ClosetManagement.ReadWrite")).Post("/api/admin/closet/:user", adminClosetController.Add)
		router.Middleware(oauthmw.RequireScopes("ClosetManagement.ReadWrite")).Delete("/api/admin/closet/:user", adminClosetController.Remove)
		// PHP Route::any：POST 由 Page 处理器内部转给保存逻辑，其余方法渲染页面。
		router.Any("/admin/options", adminOptionsController.OptionsPage)
		router.Any("/admin/customize", adminOptionsController.CustomizePage)
		router.Any("/admin/score", adminOptionsController.ScorePage)
		router.Any("/admin/resource", adminOptionsController.ResourcePage)
		router.Get("/admin/i18n", adminController.I18nPage)
		router.Get("/admin/i18n/list", translationsController.List)
		router.Post("/admin/i18n", translationsController.Create)
		router.Put("/admin/i18n/:line", translationsController.Update)
		router.Delete("/admin/i18n/:line", translationsController.Delete)
		router.Get("/admin/communications", communicationsController.CommunicationsPage)
		router.Post("/admin/communications", communicationsController.Store)
		// Laravel 路由：throttle:90,1 / throttle:30,1。
		router.Middleware(oauthmw.Throttle(90, 60)).Post("/admin/communications/preview", communicationsController.Preview)
		router.Middleware(oauthmw.Throttle(30, 60)).Post("/admin/communications/import", communicationsController.Import)
		router.Put("/admin/communications/:communication", communicationsController.Update)
		router.Post("/admin/communications/update/:communication", communicationsController.Update)
		router.Post("/admin/communications/:communication/withdraw", communicationsController.Withdraw)
		router.Get("/user/inbox", userController.InboxPage)
		router.Get("/user/inbox/:id", userController.MessagePage)
		router.Middleware(oauthmw.RequireScopes("Notification.Read")).Get("/api/user/notifications", notificationController.Unread)
		router.Get("/admin", adminController.IndexPage)
		router.Get("/admin/chart", adminController.Chart)
		router.Get("/admin/status", adminController.Status)
		router.Get("/admin/plugins/data", pluginController.Data)
		router.Get("/admin/plugins/manage", adminController.PluginsPage)
		router.Post("/admin/plugins/manage", pluginController.Manage)
		router.Get("/admin/plugins/readme/:name", pluginController.Readme)
		router.Any("/admin/plugins/config/:name", pluginController.Config)
		router.Post("/admin/plugins/upload", pluginController.Upload)
		router.Post("/admin/plugins/wget", pluginController.Wget)
		router.Get("/admin/plugins/market", adminController.MarketPage)
		router.Get("/admin/plugins/market/list", marketController.List)
		router.Post("/admin/plugins/market/download", marketController.Download)
		router.Get("/admin/update", updateController.UpdatePage)
		router.Post("/admin/update/download", updateController.Download)
		// Laravel 路由：throttle:6,1 / throttle:3,1。
		router.Middleware(oauthmw.Throttle(6, 60)).Post("/admin/update/upload", updateController.Upload)
		router.Middleware(oauthmw.Throttle(3, 60)).Post("/admin/update/install", updateController.Install)
		router.Get("/user", userController.Index)
		router.Post("/admin/notifications/send", notificationController.Send)
		router.Middleware(oauthmw.RequireScopes("Notification.ReadWrite")).Post("/api/admin/notifications", notificationController.Send)
		router.Post("/user/notifications/:id", notificationController.Read)
		router.Middleware(oauthmw.RequireScopes("Notification.Read")).Post("/api/user/notifications/:id", notificationController.Read)
		router.Get("/oauth/scopes", oauthController.Scopes)
		router.Get("/oauth/clients", oauthController.Clients)
		router.Post("/oauth/clients", oauthController.StoreClient)
		router.Put("/oauth/clients/:client_id", oauthController.UpdateClient)
		router.Delete("/oauth/clients/:client_id", oauthController.DeleteClient)
		router.Get("/oauth/authorize", oauthController.Authorize)
		router.Post("/oauth/authorize", oauthController.Approve)
		router.Delete("/oauth/authorize", oauthController.Deny)
		router.Get("/oauth/tokens", oauthController.Tokens)
		router.Delete("/oauth/tokens/:token_id", oauthController.DeleteToken)
		router.Post("/oauth/token/refresh", oauthController.RefreshTransientToken)
		router.Get("/oauth/personal-access-tokens", oauthController.PersonalTokens)
		router.Post("/oauth/personal-access-tokens", oauthController.StorePersonalToken)
		router.Delete("/oauth/personal-access-tokens/:token_id", oauthController.DeletePersonalToken)
		router.Get("/user/oauth/manage", userController.OAuthPage)
		router.Get("/user/profile", userController.ProfilePage)
		router.Post("/user/profile", userController.HandleProfile)
		router.Post("/user/profile/avatar", userController.SetAvatar)
		router.Get("/user/score-info", userController.ScoreInfo)
		router.Post("/user/sign", userController.Sign)
		router.Put("/user/dark-mode", userController.DarkMode)
	})

	facades.Route().Get("/:player", textures.PlayerJSON)

	facades.Route().Static("app", "./public/app")
	facades.Route().Static("public", "./public")

	// 与 PHP RouteServiceProvider 一致：核心路由注册完成后派发 ConfigureRoutes，
	// 插件经 Hook::addRoute 注册的回调此时收到路由器；再派发事件给直接监听者。
	plugin.DefaultHook.ApplyRoutes(facades.Route())
	plugin.DefaultDispatcher.Dispatch(plugin.Event{
		Name:    plugin.EventConfigureRoutes,
		Payload: facades.Route(),
	})
}
